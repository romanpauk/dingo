"""Builds the model baseline: the outcome of every cell, asked from the library.

A cell is container x scope x stored form x leaf x interfaces declared x
selection x operation x interface x request. The library answers each cell; nothing here decides
what should work:

- invalid: the request cannot be spelled in C++, such as an abstract type
  held by value
- not_registrable: the library rejects the registration (binding_model::valid),
  so the probe does not register it
- rejected: the library rejects the request or the registration at compile
  time with a static_assert; its message is kept
- does_not_compile: the request fails to compile otherwise, which is a defect;
  the first error is kept
- crashed: the probe of the request did not exit, which is a defect
- violated: the request resolved, and the result is wrong: it does not reach
  the registered leaf, a kept instance is not kept, a unique one is, a kept
  class refers to a leaf that is gone, or the probe leaks
- resolved: the request resolved and the result is right
- type_not_found, type_not_convertible, type_ambiguous, exception: the
  exception the request threw
- unprobed, unreachable: a request the registration publishes that no probe
  makes, or that selects another binding; both are defects

The containers must agree: a request that one resolves the other resolves,
unless one of them does not accept the registration. The probe fails when a
cell is a defect or the containers disagree.

The model, the templates that spell it in C++ and the driver that compiles
and runs the probes are in generator/.
"""

import argparse
import concurrent.futures
from dataclasses import replace
import os
from pathlib import Path
import shlex
import sys

sys.path.insert(0, str(Path(__file__).parent))

from generator import driver, report  # noqa: E402
from generator.dimensions import (Category, Container,  # noqa: E402
                                  Outcome, Position, Shape)
from generator.registrations import (covering,  # noqa: E402
                                     probe_registration, registrations)
from generator.survey import survey  # noqa: E402

DIMENSIONS = ("container", "scope", "form", "leaf", "interfaces", "selection",
              "operation", "interface", "request")


def disagreements(cells):
    """The cells one container resolves and the other does not, though both
    accept the registration."""
    outcomes = {}
    for cell in cells:
        container, rest = cell["cell"].split("/", 1)
        outcomes.setdefault(rest, {})[container] = cell["outcome"]
    found = []
    for rest, by_container in sorted(outcomes.items()):
        if len(by_container) != len(Container) or any(
                outcome in (Outcome.NOT_REGISTRABLE, Outcome.INVALID)
                for outcome in by_container.values()):
            continue
        if len({outcome == Outcome.RESOLVED
                for outcome in by_container.values()}) > 1:
            found.append((rest, by_container))
    return found


def write_report(path, cells, disagreeing):
    """Counts by dimension, a table per container, leaf, interfaces,
    selection and operation, and the compile-time outcomes with their
    messages."""
    lines = [
        "# Model baseline", "",
        "Generated by test/model/probe.py. Legend: " + ", ".join(
            f"`{mark}` {outcome.value}"
            for outcome, mark in report.MARKS.items()), "",
        f"{len(cells)} cells.", "",
    ]
    for dimension in DIMENSIONS[:-1]:
        lines += report.counts_table(cells, DIMENSIONS, dimension)
    patterns = [category.value.replace("X", shape.value) for shape in Shape
                for category in Category]
    rows = {}
    for cell in cells:
        (container, scope, form, leaf, interfaces, selection, operation,
         bound, request) = cell["cell"].split("/")
        rows.setdefault((container, leaf, interfaces, selection, operation),
                        {}).setdefault((scope, form, bound), {})[request] = (
                            report.mark(cell["outcome"]))
    for key in sorted(rows):
        container, leaf, interfaces, selection, operation = key
        lines += [
            f"## {container} container, {leaf} leaf, {interfaces} "
            f"interfaces, {selection}, {operation}", "",
            "| scope / stored / interface | " + " | ".join(
                f"`{r}`" for r in patterns) + " |",
            "|---|" + "---|" * len(patterns),
        ]
        for (scope, form, bound), row in rows[key].items():
            lines.append(f"| {scope} / {form} / `{bound}` | " + " | ".join(
                row.get(r, "?") for r in patterns) + " |")
        lines.append("")
    lines += ["## Container disagreements", ""]
    lines += [f"- `{rest}`: " + ", ".join(f"{c} {o}" for c, o in by.items())
              for rest, by in disagreeing] or ["None."]
    lines += [""] + report.compile_time_outcomes(cells)
    path.write_text("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("output", type=Path, help="the baseline JSON")
    parser.add_argument("--work", type=Path, required=True)
    parser.add_argument("--compiler", default=os.environ.get("CXX", "c++"))
    parser.add_argument("--flags", default="-std=c++17 -O0 -Iinclude -Itest",
                        help="compiler flags, with include paths")
    parser.add_argument("--jobs", type=int, default=os.cpu_count())
    parser.add_argument(
        "--only", default="",
        help="probe only the registrations whose name contains this text")
    parser.add_argument(
        "--cover", choices=("all", "pairs", "triples"), default="all",
        help="probe every registration, or the registrations that hold every "
        "combination of values of two or three of scope, stored form, leaf, "
        "interfaces and selection, in both containers")
    options = parser.parse_args()
    options.work.mkdir(parents=True, exist_ok=True)
    flags = (shlex.split(options.flags) +
             driver.error_limit_flags(options.compiler))
    flags = driver.precompile_header(options.compiler, flags, options.work,
                                     "probe.h") + flags

    units = [unit for unit in registrations() if options.only in unit.name]
    if options.cover != "all":
        covered = covering({"pairs": 2, "triples": 3}[options.cover])
        units = [unit for unit in units if unit.dimensions in covered]
    bound = survey(options.compiler, flags, options.work, units)
    units = [replace(unit, bound=bound.get(unit.survey_key, ()))
             for unit in units]
    # The costliest first, so that none of them is left for the end: the
    # runtime container's, and of those the kept consumers'.
    tasks = sorted(((unit, position) for unit in units
                    for position in Position),
                   key=lambda task: (task[0].container is not Container.RUNTIME,
                                     task[1].kept_by is None))
    cells = []
    with concurrent.futures.ThreadPoolExecutor(options.jobs) as executor:
        for outcomes in executor.map(
                lambda task: probe_registration(options.compiler, flags,
                                                options.work, *task), tasks):
            cells += outcomes
    cells = report.write(options.output, cells)
    disagreeing = disagreements(cells)
    write_report(options.output.with_suffix(".md"), cells, disagreeing)
    return report.summarize(
        cells, [f"{rest}: {by}" for rest, by in disagreeing],
        options.output.with_suffix(".md"))


if __name__ == "__main__":
    sys.exit(main())
