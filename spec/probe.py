"""Builds the model baseline: the outcome of every cell, asked from the library
and compared with what the semantics expect.

A cell is container x scope x stored form x leaf x interfaces declared x
selection x operation x interface x request. The library answers each cell:

- invalid: the request cannot be spelled in C++, such as an abstract type
  held by value
- not_registrable: the library rejects the registration (binding_model::valid),
  so the probe does not register it
- rejected: the library rejects the request or the registration at compile
  time with a static_assert; its message is kept
- does_not_compile: the request fails to compile otherwise, which is a defect;
  the first error is kept
- crashed: the probe of the request did not exit, which is a defect
- violated: the request resolved, and the result is wrong: it does not reach
  the registered leaf, a kept instance is not kept, a unique one is, a kept
  class refers to a leaf that is gone, or the probe leaks
- resolved: the request resolved and the result is right
- type_not_found, type_not_convertible, type_ambiguous, exception: the
  exception the request threw
- unprobed, unreachable: a request the registration publishes that no probe
  makes, or that selects another binding; both are defects

generator/semantics.py says what each cell should be: whether the library
accepts the registration and the interfaces it binds, whether the request
resolves, and how it fails when it does not. A cell a known limitation of the
library keeps from resolving is limited; one that resolves although a
limitation says it does not is a stale limitation, and one with another
outcome than the expected one is unexpected; both are defects. The probe fails
when a cell is a defect or a registration binds other interfaces.

The probes, the templates that spell them in C++ and the driver that
compiles and runs them are in generator/; the C++ headers the programs
include are in test/model.
"""

import argparse
import concurrent.futures
import os
import re
from pathlib import Path
import shlex
import sys

# The root, which the specification is a package of.
sys.path.insert(0, str(Path(__file__).parents[1]))

from spec import semantics  # noqa: E402
from spec.generator import driver, report  # noqa: E402
from spec.generator.registrations import (  # noqa: E402
    Registration, apply_semantics, covering, probe_registrations,
    registrations)
from spec.generator.survey import survey  # noqa: E402
from spec.vocabulary import (Category, Container,  # noqa: E402
                             InterfaceSet, Leaf, Position, Selection, Shape,
                             StoredForm)

# The layers a probe checks alone, by the registrations and the probes of
# them it makes: what every registration stores, requested as it is, which
# only the storage copies or moves; and the leaf of a plain registration,
# which only passing it on in its position does. A factory leaf is copied
# and moved as a copyable one. As in a cover, only the registrations the
# library is to accept are probed.
LAYERS = {
    "storage": (lambda unit: unit.selection is Selection.PLAIN,
                Registration.stores),
    "resolution": (lambda unit: (unit.form is StoredForm.PLAIN and
                                 unit.interfaces_declared is
                                 InterfaceSet.DEFAULT and
                                 unit.leaf is not Leaf.FACTORY),
                   Registration.passes),
}

DIMENSIONS = ("container", "scope", "form", "leaf", "interfaces", "selection",
              "operation", "interface", "request")


def write_report(path, cells, mismatches):
    """Counts by dimension, a table per container, leaf, interfaces,
    selection and operation, and the compile-time outcomes with their
    messages."""
    lines = [
        "# Model baseline", "",
        "Generated by spec/probe.py. Legend: " + ", ".join(
            f"`{mark}` {outcome.value}"
            for outcome, mark in report.MARKS.items()), "",
        f"{len(cells)} cells.", "",
    ]
    for dimension in DIMENSIONS[:-1]:
        lines += report.counts_table(cells, DIMENSIONS, dimension)
    present = {cell["cell"].rsplit("/", 1)[1] for cell in cells}
    patterns = [pattern for pattern in (
        category.value.replace("X", shape.value) for shape in Shape
        for category in Category) if pattern in present]
    rows = {}
    for cell in cells:
        (container, scope, form, leaf, interfaces, selection, operation,
         bound, request) = cell["cell"].split("/")
        rows.setdefault((container, leaf, interfaces, selection, operation),
                        {}).setdefault((scope, form, bound), {})[request] = (
                            report.mark(cell["outcome"]))
    for key in sorted(rows):
        container, leaf, interfaces, selection, operation = key
        lines += [
            f"## {container} container, {leaf} leaf, {interfaces} "
            f"interfaces, {selection}, {operation}", "",
            "| scope / stored / interface | " + " | ".join(
                f"`{r}`" for r in patterns) + " |",
            "|---|" + "---|" * len(patterns),
        ]
        for (scope, form, bound), row in rows[key].items():
            lines.append(f"| {scope} / {form} / `{bound}` | " + " | ".join(
                row.get(r, "?") for r in patterns) + " |")
        lines.append("")
    lines += ["## Bindings other than expected", ""]
    lines += [f"- `{line}`" for line in mismatches] or ["None."]
    lines += [""] + report.compile_time_outcomes(cells)
    path.write_text("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("output", type=Path, help="the baseline JSON")
    parser.add_argument("--work", type=Path, required=True)
    parser.add_argument("--compiler", default=os.environ.get("CXX", "c++"))
    parser.add_argument("--flags", default="-std=c++17 -O0 -Iinclude -Itest",
                        help="compiler flags, with include paths")
    parser.add_argument("--jobs", type=int,
                        default=driver.default_jobs())
    parser.add_argument(
        "--only", default="",
        help="probe only the registrations whose name matches this regular "
        "expression")
    parser.add_argument(
        "--cover", choices=("all", "pairs", "triples"), default="all",
        help="probe every registration, or the registrations that hold every "
        "combination of values of two or three of scope, stored form, leaf, "
        "interfaces and selection, in both containers")
    parser.add_argument(
        "--layer", choices=sorted(LAYERS),
        help="probe only the copies and the moves of a layer: what every "
        "registration stores, requested as it is, or the leaf of a plain "
        "registration, in every position")
    options = parser.parse_args()
    options.work.mkdir(parents=True, exist_ok=True)
    flags = (shlex.split(options.flags) +
             driver.error_limit_flags(options.compiler))
    flags = driver.precompile_header(options.compiler, flags, options.work,
                                     "probe.h") + flags

    units = [unit for unit in registrations()
             if re.search(options.only, unit.name)]
    if options.cover != "all":
        covered = covering({"pairs": 2, "triples": 3}[options.cover])
        units = [unit for unit in units if unit.dimensions in covered]
    selected = None
    if options.layer:
        layered, selected = LAYERS[options.layer]
        units = [unit for unit in units if layered(unit) and
                 semantics.registrable(unit.container, *unit.dimensions[:4])]
    mismatches = [f"{unit.survey_key} binds other interfaces than "
                  f"{[bound.name for bound in unit.interfaces()]}"
                  for unit in survey(options.compiler, flags, options.work,
                                     units)]
    # The costliest first, so that none of them is left for the end: the
    # runtime container's, and of those the kept consumers'.
    tasks = sorted(((unit, position) for unit in units
                    for position in Position),
                   key=lambda task: (task[0].container is not Container.RUNTIME,
                                     task[1].kept_by is None))
    driver.set_jobs(options.jobs)
    with concurrent.futures.ThreadPoolExecutor(options.jobs) as executor:
        cells = probe_registrations(
            options.compiler, flags, options.work, tasks, selected,
            lambda function, items: list(executor.map(function, items)))
    cells = report.write(options.output, apply_semantics(cells, units))
    write_report(options.output.with_suffix(".md"), cells, mismatches)
    return report.summarize(cells, mismatches,
                            options.output.with_suffix(".md"))


if __name__ == "__main__":
    sys.exit(main())
