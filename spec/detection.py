"""Builds the constructor detection baseline: what detection says about every
class generated around a request of the grammar, and what constructing it
does.

A parameter is every shape of every supported leaf, copyable, move-only and
an abstract interface, each plain, annotated and keyed, in every category.
It is the parameter of a class of each kind: a constructor, an explicit
constructor, an aggregate member and the two parameters of a constructor.
The library answers each cell:

- detected or misdetected: what shape and signature detection say about the
  class, against the constructor the generator wrote
- resolved, type_not_found, ...: the class made through resolve, construct
  and invoke of an unregistered class and through a shared registration of
  it, in both containers over a few registrations of the leaf, with the
  constructor an explicit factory names, the one shape detection finds and
  the one signature detection finds

A class made with a detected constructor has to make what it does with the
explicit one. The probe fails on a defect (does_not_compile, crashed,
violated, misdetected) and on a disagreement with the explicit constructor.

The model, the templates and the driver are in generator/.
"""

import argparse
import concurrent.futures
import os
import re
from pathlib import Path
import shlex
import sys

# The root, which the specification is a package of.
sys.path.insert(0, str(Path(__file__).parents[1]))

from spec.generator import driver, report  # noqa: E402
from spec.generator.detection import (  # noqa: E402
    apply_limitations, disagreements, probe_unit, units)

DIMENSIONS = ("family", "container", "provider", "leaf", "selection", "kind",
              "operation", "request")


def write_report(path, cells, disagreeing):
    lines = ["# Constructor detection baseline", "",
             "Generated by spec/detection.py.", "",
             f"{len(cells)} cells.", ""]
    for dimension in DIMENSIONS[1:-1]:
        lines += report.counts_table(cells, DIMENSIONS, dimension)
    lines += ["## Disagreements with the explicit constructor", ""]
    lines += [f"- `{line}`" for line in disagreeing] or ["None."]
    lines += [""] + report.compile_time_outcomes(cells)
    path.write_text("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("output", type=Path, help="the baseline JSON")
    parser.add_argument("--work", type=Path, required=True)
    parser.add_argument("--compiler", default=os.environ.get("CXX", "c++"))
    parser.add_argument("--flags", default="-std=c++17 -O0 -Iinclude -Itest",
                        help="compiler flags, with include paths")
    parser.add_argument("--jobs", type=int, default=os.cpu_count())
    parser.add_argument(
        "--only", default="",
        help="probe only the units whose name matches this regular expression")
    parser.add_argument(
        "--cover", choices=("all", "pairs", "triples"), default="all",
        help="make the classes over every leaf, selection, kind and provider, "
        "or over those that hold every combination of values of two or three "
        "of them")
    options = parser.parse_args()
    options.work.mkdir(parents=True, exist_ok=True)
    flags = (shlex.split(options.flags) +
             driver.error_limit_flags(options.compiler))
    flags = driver.precompile_header(options.compiler, flags, options.work,
                                     "detection.h") + flags

    strength = {"all": None, "pairs": 2, "triples": 3}[options.cover]
    selected = [unit for unit in units(strength)
                if re.search(options.only, unit.name)]
    # The costliest first: the runtime container's.
    selected.sort(key=lambda unit: unit.container_name != "runtime")
    cells = []
    driver.set_jobs(options.jobs)
    with concurrent.futures.ThreadPoolExecutor(options.jobs) as executor:
        for outcomes in executor.map(
                lambda unit: probe_unit(options.compiler, flags, options.work,
                                        unit), selected):
            cells += outcomes
    cells = report.write(options.output, apply_limitations(cells, selected))
    disagreeing = disagreements(cells, selected)
    write_report(options.output.with_suffix(".md"), cells, disagreeing)
    return report.summarize(cells, disagreeing,
                            options.output.with_suffix(".md"))


if __name__ == "__main__":
    sys.exit(main())
