"""Checks what the binding of every registration derives for every request,
as the code compiles, against the specification.

A cell is scope x stored form x leaf x interfaces declared x interface x
request. Each cell has one of these outcomes in a binding:

- published: it derives the request for as long as the container, which the
  caller may take
- placed: it derives it only for as long as the request
- unpublished: it derives it not at all
- does_not_compile: the registration does not compile, which is a defect

A published or placed request the specification resolves in no position is
unexpected, and so is one that is not published although the specification
resolves it for the caller; both are defects.

The static container runs the derivation of each cell; the runtime container
selects its conversion of the tables of the binding and of the request as it
runs. Each cell records what the runtime container selects for each lifetime,
of no container: whether it finds a conversion, its copies and moves of the
leaf and the objects it keeps and makes, whether what satisfies the request may
be absent, how the request takes it, whether its address lives as long as the
container, and how the request takes the value. Any of these apart from the
derivation is a defect. A request the runtime container does not model, which
the derivation finds neither, is unmodeled.

Each cell also records how C++ itself builds the request from what the
binding holds. A request C++ builds that the specification, without the
limitations of the library, resolves nowhere is unexpected, unless the
specification rejects it on purpose; so is one it rejects on purpose and
resolves.

How a derivation copies and moves the leaf is what spec/execution_check.py checks.

No container is made and nothing resolves, so every registration is checked,
many in one program: spec/probe.py checks what resolutions do.
"""

import argparse
import concurrent.futures
import os
from pathlib import Path
import re
import shlex
import sys

# The root, which the specification is a package of.
sys.path.insert(0, str(Path(__file__).parents[1]))

from spec.generator import driver, report  # noqa: E402
from spec.generator.conversions import (  # noqa: E402
    apply_semantics, batch_name, compile_runtime, compile_units, expect_all,
    runtime_outcome, runtime_name, runtime_programs, units)

DIMENSIONS = ("scope", "form", "leaf", "interfaces", "interface", "request")


def write_report(path, cells, runtime):
    lines = [
        "# Conversion layer", "",
        "Generated by spec/conversion.py.", "",
        f"{len(cells)} cells.", "",
    ]
    for dimension in DIMENSIONS[:-1]:
        lines += report.counts_table(
            [cell for cell in cells if "/published/" not in cell["cell"]],
            DIMENSIONS, dimension)
    counts = runtime_counts(cells) if runtime else []
    if counts:
        lines += ["## Runtime container", "",
                  "| runtime | cells |", "|---|---:|"]
        lines += [f"| `{outcome}` | {count} |" for outcome, count in counts]
    lines += [""] + report.compile_time_outcomes(cells)
    path.write_text("\n".join(lines) + "\n")


def runtime_counts(cells):
    """The cells by how the runtime container selects their request,
    compared with the derivation."""
    counts = {}
    for cell in cells:
        outcome = runtime_outcome(cell)
        if outcome is not None:
            counts[outcome] = counts.get(outcome, 0) + 1
    return sorted(counts.items(), key=lambda item: -item[1])


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("output", type=Path, help="the cells as JSON")
    parser.add_argument("--work", type=Path, required=True)
    parser.add_argument("--compiler", default=os.environ.get("CXX", "c++"))
    parser.add_argument("--flags", default="-std=c++17 -O0 -Iinclude -Itest",
                        help="compiler flags, with include paths")
    parser.add_argument("--jobs", type=int,
                        default=driver.default_jobs())
    parser.add_argument("--cells", type=int, default=1500,
                        help="the cells a program holds at most, of whole "
                        "registrations: what it compiles grows with them")
    parser.add_argument(
        "--only", default="",
        help="check only the registrations whose name matches this regular "
        "expression")
    parser.add_argument(
        "--no-runtime", dest="runtime", action="store_false",
        help="compare no conversion the runtime container selects with the "
        "derivation")
    options = parser.parse_args()
    options.work.mkdir(parents=True, exist_ok=True)
    driver.open_cache(options.work / "programs")
    flags = (shlex.split(options.flags) +
             driver.error_limit_flags(options.compiler))
    flags = driver.precompile_header(options.compiler, flags, options.work,
                                     "conversion.h") + flags

    checked = [unit for unit in units() if re.search(options.only, unit.name)]
    batches = []
    size = 0
    for unit in checked:
        count = len(unit.cells())
        # A program is of one scope, so that it reads that scope alone.
        if (not batches or size + count > options.cells or
                batches[-1][0].scope is not unit.scope):
            batches.append([])
            size = 0
        batches[-1].append(unit)
        size += count
    # The largest first, so that none of them is left for the end.
    order = sorted(range(len(batches)),
                   key=lambda index: -sum(len(unit.cells())
                                          for unit in batches[index]))
    cells = []
    driver.set_jobs(options.jobs)
    expect_all(checked, options.jobs)
    programs = runtime_programs(checked) if options.runtime else []
    selected = {}
    # The runtime programs compile their parts at once, each in a thread
    # of its own that waits for a compiler as a program does.
    with concurrent.futures.ThreadPoolExecutor(
            max(len(programs), 1)) as runtime_executor, \
            concurrent.futures.ThreadPoolExecutor(options.jobs) as executor:
        pending = [runtime_executor.submit(
            compile_runtime, options.compiler, flags, options.work,
            runtime_name(index), program)
            for index, program in enumerate(programs)]
        for records in executor.map(
                lambda item: compile_units(options.compiler, flags,
                                           options.work, batch_name(item[0]),
                                           item[1]),
                [(index, batches[index]) for index in order]):
            cells += records
        for future in pending:
            selected.update(future.result())
    for cell in cells:
        cell.update(selected.get(cell["cell"], {}))
    cells = report.write(options.output, apply_semantics(cells, checked,
                                                         options.runtime))
    write_report(options.output.with_suffix(".md"), cells, options.runtime)
    driver.close_cache(prune=not options.only)
    if options.runtime:
        print("runtime container: " + ", ".join(
            f"{count} {outcome}" for outcome, count in runtime_counts(cells)),
            file=sys.stderr)
    return report.summarize(cells, [], options.output.with_suffix(".md"))


if __name__ == "__main__":
    sys.exit(main())
