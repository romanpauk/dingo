"""Checks what the conversion layer of every binding answers every request,
as the code compiles, against the specification.

A cell is scope x stored form x leaf x interfaces declared x interface x
request. The conversion layer answers each cell:

- published: the request lists of the binding select a resolution of the
  request, and its conversion is available
- unconvertible: they select one whose conversion is not available
- unpublished: they select none
- diverged: the static and the runtime container select differently, which
  is a defect
- does_not_compile: the registration does not compile, which is a defect

A published request the specification resolves in no position is unexpected,
and so is one that is not published although the specification resolves it
for the caller; both are defects. A request the registration publishes that
no cell asks for is unprobed, and one that selects another binding
unreachable, as in the model probe.

No container is made and nothing resolves, so every registration is checked,
many in one program: spec/probe.py checks what resolutions do.
"""

import argparse
import concurrent.futures
import os
from pathlib import Path
import re
import shlex
import sys

# The root, which the specification is a package of.
sys.path.insert(0, str(Path(__file__).parents[1]))

from spec.generator import driver, report  # noqa: E402
from spec.generator.conversions import (  # noqa: E402
    apply_semantics, batch_name, compile_units, units)

DIMENSIONS = ("scope", "form", "leaf", "interfaces", "interface", "request")


def write_report(path, cells):
    lines = [
        "# Conversion layer", "",
        "Generated by spec/conversion.py.", "",
        f"{len(cells)} cells.", "",
    ]
    for dimension in DIMENSIONS[:-1]:
        lines += report.counts_table(
            [cell for cell in cells if "/published/" not in cell["cell"]],
            DIMENSIONS, dimension)
    lines += [""] + report.compile_time_outcomes(cells)
    path.write_text("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("output", type=Path, help="the cells as JSON")
    parser.add_argument("--work", type=Path, required=True)
    parser.add_argument("--compiler", default=os.environ.get("CXX", "c++"))
    parser.add_argument("--flags", default="-std=c++17 -O0 -Iinclude -Itest",
                        help="compiler flags, with include paths")
    parser.add_argument("--jobs", type=int, default=os.cpu_count())
    parser.add_argument("--batch", type=int, default=8,
                        help="the registrations compiled into one program")
    parser.add_argument(
        "--only", default="",
        help="check only the registrations whose name matches this regular "
        "expression")
    options = parser.parse_args()
    options.work.mkdir(parents=True, exist_ok=True)
    flags = (shlex.split(options.flags) +
             driver.error_limit_flags(options.compiler))
    flags = driver.precompile_header(options.compiler, flags, options.work,
                                     "conversion.h") + flags

    checked = [unit for unit in units() if re.search(options.only, unit.name)]
    batches = [checked[index:index + options.batch]
               for index in range(0, len(checked), options.batch)]
    cells = []
    driver.set_jobs(options.jobs)
    with concurrent.futures.ThreadPoolExecutor(options.jobs) as executor:
        for records in executor.map(
                lambda item: compile_units(options.compiler, flags,
                                           options.work, batch_name(item[0]),
                                           item[1]), enumerate(batches)):
            cells += records
    cells = report.write(options.output, apply_semantics(cells, checked))
    write_report(options.output.with_suffix(".md"), cells)
    return report.summarize(cells, [], options.output.with_suffix(".md"))


if __name__ == "__main__":
    sys.exit(main())
