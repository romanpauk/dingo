"""Checks what a registration whose stored object holds no leaf gives every
request the specification says is defined when a layer is empty.

A cell is container x scope x stored form x leaf x interfaces declared x
empty layer x interface x request. The stored object is empty in its
outermost layer, or in the layer that one holds: a null handle, an empty
optional, or an alternative type that holds the other alternative. Each
probed request resolves through invoke:

- defined: it gives what holds no leaf, as the specification says
- violated: it gives what holds a leaf
- unexpected: it throws, which goes through an element that is absent
- does_not_compile, crashed: defects

A request that is not defined when a layer is empty may fail in any way, so
it is not probed.
"""

import argparse
import concurrent.futures
import os
from pathlib import Path
import re
import shlex
import sys

# The root, which the specification is a package of.
sys.path.insert(0, str(Path(__file__).parents[1]))

from spec.generator import driver, report  # noqa: E402
from spec.generator.emptiness import (  # noqa: E402
    apply_semantics, batch_name, compile_units, units)

DIMENSIONS = ("container", "scope", "form", "leaf", "interfaces", "empty",
              "interface", "request")


def write_report(path, cells):
    lines = [
        "# Empty layers", "",
        "Generated by spec/emptiness.py.", "",
        f"{len(cells)} cells.", "",
    ]
    for dimension in DIMENSIONS[:-1]:
        lines += report.counts_table(cells, DIMENSIONS, dimension)
    lines += [""] + report.compile_time_outcomes(cells)
    path.write_text("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("output", type=Path, help="the cells as JSON")
    parser.add_argument("--work", type=Path, required=True)
    parser.add_argument("--compiler", default=os.environ.get("CXX", "c++"))
    parser.add_argument("--flags", default="-std=c++17 -O0 -Iinclude -Itest",
                        help="compiler flags, with include paths")
    parser.add_argument("--jobs", type=int, default=driver.default_jobs())
    parser.add_argument("--batch", type=int, default=8,
                        help="the registrations compiled into one program")
    parser.add_argument(
        "--only", default="",
        help="check only the registrations whose cell matches this regular "
        "expression")
    options = parser.parse_args()
    options.work.mkdir(parents=True, exist_ok=True)
    flags = (shlex.split(options.flags) +
             driver.error_limit_flags(options.compiler))
    flags = driver.precompile_header(options.compiler, flags, options.work,
                                     "emptiness.h") + flags

    checked = [unit for unit in units()
               if unit.probed() and re.search(options.only, unit.base)]
    batches = [checked[index:index + options.batch]
               for index in range(0, len(checked), options.batch)]
    cells = []
    driver.set_jobs(options.jobs)
    with concurrent.futures.ThreadPoolExecutor(options.jobs) as executor:
        for records in executor.map(
                lambda item: compile_units(options.compiler, flags,
                                           options.work, batch_name(item[0]),
                                           item[1]), enumerate(batches)):
            cells += records
    cells = report.write(options.output, apply_semantics(cells))
    write_report(options.output.with_suffix(".md"), cells)
    return report.summarize(cells, [], options.output.with_suffix(".md"))


if __name__ == "__main__":
    sys.exit(main())
