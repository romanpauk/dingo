"""Tests of the generator framework with fake emitters in a scratch repo."""

import os
from pathlib import Path
import shutil

import pytest

import framework
from framework import GeneratedFile

REPOSITORY = Path(__file__).resolve().parents[2]
OLD = 1_000_000_000


@pytest.fixture
def root(request):
    base = Path(
        os.environ.get(
            "DINGO_GENERATOR_TEST_DIR", REPOSITORY / "build" / "generator-test"
        )
    )
    directory = base / request.node.name
    shutil.rmtree(directory, ignore_errors=True)
    directory.mkdir(parents=True)
    yield directory
    shutil.rmtree(directory, ignore_errors=True)


def emitter(**files):
    """A fake emitter producing include/<name>.txt for each keyword."""

    def emit(spec):
        return [
            GeneratedFile(
                path=f"include/{name}.txt", content=text, spec_ids=("fake.id",)
            )
            for name, text in files.items()
        ]

    return emit


def outputs_of(root, **files):
    return framework.collect(None, [emitter(**files)], root)


def run_generate(root, **files):
    problems, written, deleted = framework.generate(root, outputs_of(root, **files))
    assert problems == []
    return written, deleted


def age(root):
    """Sets an old mtime on every file so that rewrites are detectable."""
    for file in root.rglob("*"):
        if file.is_file():
            os.utime(file, (OLD, OLD))


def mtimes(root):
    return {
        file.relative_to(root).as_posix(): file.stat().st_mtime_ns
        for file in root.rglob("*")
        if file.is_file()
    }


def test_marker_license_and_manifest_format(root):
    run_generate(root, a="alpha\n", b="beta\n")
    text = (root / "include/a.txt").read_text()
    assert text.startswith(
        "# Generated by tools/generator/generate.py from spec fake.id. "
        "Do not edit.\n#\n# This file is part of dingo project"
    )
    assert "# SPDX-License-Identifier: MIT\n#\n\nalpha\n" in text
    manifest = (root / framework.MANIFEST).read_text().splitlines()
    assert manifest[0] == "# Generated by tools/generator/generate.py. Do not edit."
    assert manifest[1:] == [
        f"{framework.sha256((root / path).read_bytes())}  {path}"
        for path in ("include/a.txt", "include/b.txt")
    ]
    assert (root / framework.MANIFEST).read_bytes().endswith(b"\n")


def test_writes_only_changed_files(root):
    run_generate(root, a="alpha\n", b="beta\n")
    age(root)
    written, deleted = run_generate(root, a="alpha\n", b="beta\n")
    assert (written, deleted) == ([], [])
    assert set(mtimes(root).values()) == {OLD * 10**9}
    written, _ = run_generate(root, a="alpha\n", b="gamma\n")
    assert written == ["include/b.txt", framework.MANIFEST]
    times = mtimes(root)
    assert times["include/a.txt"] == OLD * 10**9
    assert times["include/b.txt"] != OLD * 10**9


def test_deletes_stale_files_through_the_manifest(root):
    run_generate(root, a="alpha\n", b="beta\n")
    written, deleted = run_generate(root, a="alpha\n")
    assert deleted == ["include/b.txt"]
    assert not (root / "include/b.txt").exists()
    assert "include/b.txt" not in (root / framework.MANIFEST).read_text()


def test_deleting_the_last_file_removes_empty_directories(root):
    outputs = framework.collect(
        None,
        [
            lambda spec: [
                GeneratedFile("include/deep/er/a.txt", "x\n", ("fake.id",))
            ]
        ],
        root,
    )
    framework.generate(root, outputs)
    problems, _, deleted = framework.generate(root, {})
    assert problems == [] and deleted == ["include/deep/er/a.txt"]
    assert not (root / "include/deep").exists()


def test_refuses_to_overwrite_an_unmarked_file(root):
    (root / "include").mkdir()
    (root / "include/a.txt").write_text("hand written\n")
    problems, written, deleted = framework.generate(
        root, outputs_of(root, a="alpha\n", b="beta\n")
    )
    assert len(problems) == 1 and "include/a.txt" in problems[0]
    assert "refusing to overwrite" in problems[0]
    assert (written, deleted) == ([], [])
    assert (root / "include/a.txt").read_text() == "hand written\n"
    assert not (root / "include/b.txt").exists()
    assert not (root / framework.MANIFEST).exists()


def test_refuses_to_overwrite_a_marked_file_outside_the_manifest(root):
    run_generate(root, a="alpha\n")
    (root / framework.MANIFEST).unlink()
    problems, _, _ = framework.generate(root, outputs_of(root, a="changed\n"))
    assert len(problems) == 1 and "not in" in problems[0]


def test_refuses_to_overwrite_a_manifest_file_that_lost_its_marker(root):
    run_generate(root, a="alpha\n")
    (root / "include/a.txt").write_text("alpha\n")
    problems, _, _ = framework.generate(root, outputs_of(root, a="changed\n"))
    assert len(problems) == 1 and "marker" in problems[0]
    assert (root / "include/a.txt").read_text() == "alpha\n"


def test_refuses_to_delete_an_unmarked_file(root):
    run_generate(root, a="alpha\n", b="beta\n")
    (root / "include/b.txt").write_text("hand written\n")
    before = mtimes(root)
    problems, written, deleted = framework.generate(root, outputs_of(root, a="x\n"))
    assert len(problems) == 1 and "refusing to delete" in problems[0]
    assert (written, deleted) == ([], [])
    assert (root / "include/b.txt").read_text() == "hand written\n"
    assert mtimes(root) == before


def test_check_passes_on_a_clean_tree(root):
    run_generate(root, a="alpha\n")
    assert framework.check(root, outputs_of(root, a="alpha\n")) == []


def test_check_detects_changed_content(root):
    run_generate(root, a="alpha\n")
    problems = framework.check(root, outputs_of(root, a="changed\n"))
    assert any(
        "include/a.txt" in p and "differs from the spec output" in p
        for p in problems
    )
    assert any(p.startswith(framework.MANIFEST) for p in problems)


def test_check_detects_missing_files(root):
    run_generate(root, a="alpha\n")
    problems = framework.check(root, outputs_of(root, a="alpha\n", b="beta\n"))
    assert "include/b.txt: missing" in problems


def test_check_detects_stale_files(root):
    run_generate(root, a="alpha\n", b="beta\n")
    problems = framework.check(root, outputs_of(root, a="alpha\n"))
    assert any("include/b.txt: stale, listed in" in p for p in problems)


def test_check_detects_stale_marked_files_outside_the_manifest(root):
    run_generate(root, a="alpha\n")
    shutil.copy(root / "include/a.txt", root / "include/orphan.txt")
    problems = framework.check(root, outputs_of(root, a="alpha\n"))
    assert problems == ["include/orphan.txt: stale, carries the generated marker"]


def test_check_detects_hand_edits(root):
    run_generate(root, a="alpha\n")
    file = root / "include/a.txt"
    file.write_bytes(file.read_bytes() + b"edit\n")
    problems = framework.check(root, outputs_of(root, a="alpha\n"))
    assert problems == [
        "include/a.txt: edited by hand (differs from its hash in "
        f"{framework.MANIFEST})"
    ]


def test_check_detects_a_stale_manifest(root):
    run_generate(root, a="alpha\n")
    manifest = root / framework.MANIFEST
    manifest.write_bytes(manifest.read_bytes().replace(b"0", b"1", 1))
    problems = framework.check(root, outputs_of(root, a="alpha\n"))
    assert f"{framework.MANIFEST}: stale" in problems
    manifest.unlink()
    assert f"{framework.MANIFEST}: stale" in framework.check(
        root, outputs_of(root, a="alpha\n")
    )


def test_check_with_a_work_dir_materializes_the_output(root):
    run_generate(root, a="alpha\n")
    work = root / "work"
    assert framework.check(root, outputs_of(root, a="alpha\n"), work) == []
    assert (work / "include/a.txt").read_bytes() == (root / "include/a.txt").read_bytes()
    assert (work / framework.MANIFEST).exists()
    (root / "other").mkdir()
    (root / "other/file").write_text("x")
    with pytest.raises(framework.GeneratorError):
        framework.check(root, outputs_of(root, a="alpha\n"), root / "other")


def test_output_is_deterministic_and_sorted(root):
    first = outputs_of(root, b="beta\n", a="alpha\n")
    second = outputs_of(root, a="alpha\n", b="beta\n")
    assert first == second
    assert list(first) == sorted(first)
    assert framework.manifest_bytes(first) == framework.manifest_bytes(second)


def test_output_uses_lf_line_endings(root):
    outputs = outputs_of(root, a="alpha\r\nbeta\r\n")
    run_generate(root, a="alpha\r\nbeta\r\n")
    assert all(b"\r" not in data for data in outputs.values())
    assert b"\r" not in (root / framework.MANIFEST).read_bytes()
    assert b"\r" not in (root / "include/a.txt").read_bytes()


def test_rejects_bad_paths_and_duplicates(root):
    for path in ("/abs.txt", "../x.txt", "a/../b.txt", framework.MANIFEST):
        with pytest.raises(framework.GeneratorError):
            framework.collect(
                None, [lambda s, p=path: [GeneratedFile(p, "", ("x",))]], root
            )
    with pytest.raises(framework.GeneratorError):
        framework.collect(
            None,
            [lambda s: [GeneratedFile("a.txt", "", ("x",))] * 2],
            root,
        )


@pytest.mark.skipif(shutil.which("clang-format") is None, reason="no clang-format")
def test_cpp_is_formatted_with_the_tree_style(root):
    (root / ".clang-format").write_text("BasedOnStyle: LLVM\nIndentWidth: 4\n")
    outputs = framework.collect(
        None,
        [
            lambda s: [
                GeneratedFile(
                    "include/x.gen.h",
                    "#pragma once\nstruct   a{int   b;};\n",
                    ("fake.id",),
                )
            ]
        ],
        root,
    )
    text = outputs["include/x.gen.h"].decode()
    assert text.startswith(
        "// Generated by tools/generator/generate.py from spec fake.id. Do not edit.\n//\n"
    )
    assert "struct a {\n    int b;\n};\n" in text
    assert framework.has_marker(outputs["include/x.gen.h"])
