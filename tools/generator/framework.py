"""Generator framework: output set computation, ownership, and verification.

An emitter is a function that takes the loaded spec and returns a list of
GeneratedFile. The framework adds the marker line and the license block,
formats C++ with the clang-format found on PATH, normalizes line endings, and
computes the manifest. `generate` brings a tree in line with the output set and
`check` reports every difference without changing the tree.

Python computes all data and the Jinja templates only lay it out. The output is
deterministic: it is sorted, and it contains no timestamps, absolute paths, or
environment data.
"""

from dataclasses import dataclass
import hashlib
from pathlib import Path, PurePosixPath
import re
import shutil
import subprocess
import sys

import jinja2

GENERATOR = "tools/generator/generate.py"
MANIFEST = "spec/generated.manifest"
FIX_COMMAND = "cmake --build <build> -t generate"
TEMPLATES = Path(__file__).resolve().parent / "templates"

COMMENT_PREFIXES = {
    ".h": "//",
    ".hpp": "//",
    ".cpp": "//",
    ".cmake": "#",
    ".py": "#",
    ".txt": "#",
}
FORMATTED_SUFFIXES = (".h", ".hpp", ".cpp")
# The first line of a generated file, whatever the comment syntax.
MARKER = re.compile(
    rf"^(?://|#) Generated by {re.escape(GENERATOR)}\b.* Do not edit\.$"
)
# Directories scanned for stale files that carry the marker.
MARKED_ROOTS = ("include",)
MARKED_SUFFIXES = tuple(COMMENT_PREFIXES)


class GeneratorError(Exception):
    """An output set or tree that the generator cannot work with."""


@dataclass(frozen=True)
class GeneratedFile:
    """One generated file: a repo-relative path, its body, and its spec ids.

    The body excludes the marker line and the license block, which the
    framework adds from the spec ids.
    """

    path: str
    content: str
    spec_ids: tuple[str, ...]


def render(template, **context):
    """Renders a template from tools/generator/templates."""
    environment = jinja2.Environment(
        loader=jinja2.FileSystemLoader(str(TEMPLATES)),
        undefined=jinja2.StrictUndefined,
        keep_trailing_newline=True,
        trim_blocks=True,
        lstrip_blocks=True,
        autoescape=False,
    )
    return environment.get_template(template).render(**context)


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def has_marker(data):
    """Whether the bytes start with the generated-file marker line."""
    first = data.split(b"\n", 1)[0].decode("utf-8", errors="replace")
    return MARKER.match(first.rstrip("\r")) is not None


def comment_prefix(path):
    suffix = PurePosixPath(path).suffix
    if suffix not in COMMENT_PREFIXES:
        raise GeneratorError(f"{path}: no comment syntax for suffix '{suffix}'")
    return COMMENT_PREFIXES[suffix]


def check_path(path):
    pure = PurePosixPath(path)
    if (
        not path
        or pure.is_absolute()
        or "\\" in path
        or ".." in pure.parts
        or "." in pure.parts
        or str(pure) != path
    ):
        raise GeneratorError(f"{path!r}: not a normalized repo-relative path")
    if path == MANIFEST:
        raise GeneratorError(f"{path}: reserved for the manifest")


def clang_format(root, path, text):
    executable = shutil.which("clang-format")
    if executable is None:
        raise GeneratorError(
            "clang-format was not found on PATH; run the generator through "
            "'uv run --locked python tools/generator/generate.py'"
        )
    style = Path(root) / ".clang-format"
    arguments = [executable, f"--assume-filename={path}"]
    if style.exists():
        arguments.append(f"--style=file:{style}")
    result = subprocess.run(
        arguments, input=text.encode("utf-8"), capture_output=True, check=False
    )
    if result.returncode != 0:
        raise GeneratorError(
            f"{path}: clang-format failed: {result.stderr.decode(errors='replace')}"
        )
    return result.stdout.decode("utf-8")


def finalize(root, generated):
    """Returns the final bytes of a generated file."""
    header = render(
        "file_header.j2",
        prefix=comment_prefix(generated.path),
        generator=GENERATOR,
        spec_ids=sorted(generated.spec_ids),
    )
    text = header.rstrip("\n") + "\n\n" + generated.content.lstrip("\n")
    if PurePosixPath(generated.path).suffix in FORMATTED_SUFFIXES:
        text = clang_format(root, generated.path, text)
    text = text.replace("\r\n", "\n").rstrip("\n") + "\n"
    return text.encode("utf-8")


def collect(spec, emitters, root):
    """Runs the emitters and returns {path: bytes} sorted by path."""
    outputs = {}
    for emitter in emitters:
        for generated in emitter(spec):
            check_path(generated.path)
            if generated.path in outputs:
                raise GeneratorError(f"{generated.path}: generated twice")
            if not generated.spec_ids:
                raise GeneratorError(f"{generated.path}: names no spec entries")
            outputs[generated.path] = finalize(root, generated)
    return dict(sorted(outputs.items()))


def manifest_bytes(outputs):
    entries = [
        {"digest": sha256(data), "path": path} for path, data in sorted(outputs.items())
    ]
    text = render("manifest.j2", generator=GENERATOR, entries=entries)
    return (text.rstrip("\n") + "\n").encode("utf-8")


def read_manifest(root):
    """Returns {path: hash} of the manifest in the tree, empty when absent."""
    manifest = Path(root) / MANIFEST
    if not manifest.exists():
        return {}
    entries = {}
    for number, line in enumerate(
        manifest.read_bytes().decode("utf-8").splitlines(), 1
    ):
        if not line or line.startswith("#"):
            continue
        digest, separator, path = line.partition("  ")
        if not separator or not re.fullmatch(r"[0-9a-f]{64}", digest):
            raise GeneratorError(f"{MANIFEST}:{number}: malformed line")
        check_path(path)
        entries[path] = digest
    return entries


def marked_files(root):
    """Paths of files under MARKED_ROOTS that carry the marker."""
    found = []
    for directory in MARKED_ROOTS:
        base = Path(root) / directory
        if not base.is_dir():
            continue
        for file in sorted(base.rglob("*")):
            if file.is_file() and file.suffix in MARKED_SUFFIXES:
                if has_marker(file.read_bytes()[:512]):
                    found.append(file.relative_to(root).as_posix())
    return found


def read_if_exists(root, path):
    file = Path(root) / path
    return file.read_bytes() if file.is_file() else None


def generate(root, outputs):
    """Brings the tree in line with the outputs.

    Returns (problems, written, deleted). With problems the tree is unchanged.
    """
    root = Path(root)
    previous = read_manifest(root)
    problems = []
    for path, data in outputs.items():
        current = read_if_exists(root, path)
        if current is None or current == data:
            continue
        if path not in previous:
            problems.append(
                f"{path}: refusing to overwrite a file that is not in "
                f"{MANIFEST}; move it away or delete it"
            )
        elif not has_marker(current):
            problems.append(
                f"{path}: refusing to overwrite a file without the generated "
                "marker line; restore the marker or delete the file"
            )
    for path in sorted(set(previous) - set(outputs)):
        current = read_if_exists(root, path)
        if current is not None and not has_marker(current):
            problems.append(
                f"{path}: refusing to delete a file without the generated "
                f"marker line; remove it from {MANIFEST} or delete the file"
            )
    if problems:
        return problems, [], []

    written = []
    for path, data in outputs.items():
        if read_if_exists(root, path) != data:
            file = root / path
            file.parent.mkdir(parents=True, exist_ok=True)
            file.write_bytes(data)
            written.append(path)
    deleted = []
    for path in sorted(set(previous) - set(outputs)):
        file = root / path
        if file.is_file():
            file.unlink()
            deleted.append(path)
            parent = file.parent
            while parent != root and not any(parent.iterdir()):
                parent.rmdir()
                parent = parent.parent
    manifest = manifest_bytes(outputs)
    if read_if_exists(root, MANIFEST) != manifest:
        file = root / MANIFEST
        file.parent.mkdir(parents=True, exist_ok=True)
        file.write_bytes(manifest)
        written.append(MANIFEST)
    return [], written, deleted


def materialize(work_dir, outputs):
    """Writes the output set and its manifest below work_dir for inspection."""
    work_dir = Path(work_dir)
    sentinel = work_dir / ".generator-work"
    if work_dir.exists() and any(work_dir.iterdir()) and not sentinel.exists():
        raise GeneratorError(f"{work_dir}: not empty and not a generator work dir")
    if work_dir.exists():
        shutil.rmtree(work_dir)
    work_dir.mkdir(parents=True)
    sentinel.write_bytes(b"")
    for path, data in {**outputs, MANIFEST: manifest_bytes(outputs)}.items():
        file = work_dir / path
        file.parent.mkdir(parents=True, exist_ok=True)
        file.write_bytes(data)


def check(root, outputs, work_dir=None):
    """Returns the problems found between the tree and the outputs."""
    root = Path(root)
    if work_dir is not None:
        materialize(work_dir, outputs)
        outputs = {
            path: (Path(work_dir) / path).read_bytes() for path in outputs
        }
    previous = read_manifest(root)
    problems = []
    for path, data in outputs.items():
        current = read_if_exists(root, path)
        if current is None:
            problems.append(f"{path}: missing")
        elif current != data:
            if path in previous and sha256(current) != previous[path]:
                problems.append(
                    f"{path}: edited by hand (differs from its hash in "
                    f"{MANIFEST})"
                )
            else:
                problems.append(f"{path}: content differs from the spec output")
    for path in sorted(set(previous) - set(outputs)):
        problems.append(f"{path}: stale, listed in {MANIFEST} but not generated")
    for path in sorted(set(marked_files(root)) - set(outputs) - set(previous)):
        problems.append(f"{path}: stale, carries the generated marker")
    if read_if_exists(root, MANIFEST) != manifest_bytes(outputs):
        problems.append(f"{MANIFEST}: stale")
    return problems


def load_spec(root):
    """Imports the spec package of the tree and returns its loaded spec."""
    sys.path.insert(0, str(root))
    import spec

    return spec.load_spec()
