"""Compare the per-storage resolve outcomes with the model expectation.

The resolve generator writes a manifest of every call it emitted and the
generated tests write one outcome line per call. This report separates:

- covered: the model expects the call and the implementation resolved it;
- overclaim: the model expects the call and it threw;
- declared gap: the model marked it as an exception and it threw;
- stale declaration: the model marked it as an exception and it resolved.

The overclaims are the model surface that has to be tightened or declared.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path


def read_manifest(path: Path) -> dict[str, dict[str, object]]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    calls: dict[str, dict[str, object]] = {}
    for shard in payload["shards"]:
        for test in shard["tests"]:
            for call in test["calls"]:
                calls[call["name"]] = {
                    "name": call["name"],
                    "request": call["request"],
                    "declared": bool(call["declared"]),
                    "declared_reason": str(call.get("declared_reason", "")),
                    "scope": test["scope"],
                    "storage": test["storage"],
                    "binding": test["binding"],
                    "traits": test["traits"],
                    "form": test["form"],
                    "shard": shard["name"],
                }
    return calls


def read_outcomes(paths: list[Path]) -> dict[str, dict[str, object]]:
    outcomes: dict[str, dict[str, object]] = {}
    for path in paths:
        for line in path.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            row = json.loads(line)
            outcomes[row["name"]] = row
    return outcomes


def _access(request: str) -> str:
    request = request.strip()
    if request.endswith("&&"):
        return "rvalue"
    if request.endswith("&"):
        return "lvalue"
    if request.endswith("*"):
        return "pointer"
    return "value"


def compare(
    manifest: dict[str, dict[str, object]],
    outcomes: dict[str, dict[str, object]],
) -> dict[str, object]:
    overclaims = []
    declared_failures = []
    declared_successes = []
    covered = 0
    missing = []
    for name, expected in manifest.items():
        outcome = outcomes.get(name)
        if outcome is None:
            missing.append(name)
            continue
        ok = outcome["result"] == "ok"
        if expected["declared"]:
            (
                declared_successes if ok else declared_failures
            ).append(expected)
        elif ok:
            covered += 1
        else:
            overclaims.append(
                {
                    **expected,
                    "result": outcome["result"],
                    "access": _access(str(expected["request"])),
                }
            )
    return {
        "totals": {
            "expected": len(manifest),
            "actual": len(outcomes),
            "covered": covered,
            "overclaim": len(overclaims),
            "declared_failure": len(declared_failures),
            "declared_success": len(declared_successes),
            "missing": len(missing),
        },
        "overclaims": overclaims,
        "declared_failures": declared_failures,
        "declared_successes": declared_successes,
        "missing": missing,
        "overclaim_by_form": dict(
            Counter(str(row["form"]) for row in overclaims)
        ),
        "overclaim_by_binding": dict(
            Counter(str(row["binding"]) for row in overclaims)
        ),
        "overclaim_by_traits": dict(
            Counter(str(row["traits"]) for row in overclaims)
        ),
        "overclaim_by_access": dict(
            Counter(str(row["access"]) for row in overclaims)
        ),
        "declared_failure_by_reason": dict(
            Counter(str(row.get("declared_reason", "")) for row in declared_failures)
        ),
        "declared_success_by_reason": dict(
            Counter(str(row.get("declared_reason", "")) for row in declared_successes)
        ),
    }


def render(report: dict[str, object]) -> str:
    totals = report["totals"]
    lines = [
        "# Per-storage resolve gaps",
        "",
        "Generated by `python -m tools.model.report.resolves`.",
        "",
        "| metric | calls |",
        "| --- | ---: |",
        f"| expected | {totals['expected']} |",
        f"| actual | {totals['actual']} |",
        f"| covered | {totals['covered']} |",
        f"| overclaim | {totals['overclaim']} |",
        f"| declared gap | {totals['declared_failure']} |",
        f"| stale declaration | {totals['declared_success']} |",
        f"| missing outcome | {totals['missing']} |",
        "",
        "## Overclaims by form",
        "",
    ]
    for name, count in sorted(
        report["overclaim_by_form"].items(), key=lambda item: -item[1]
    ):
        lines.append(f"- `{name}`: {count}")
    lines += ["", "## Overclaims by access", ""]
    for name, count in sorted(
        report["overclaim_by_access"].items(), key=lambda item: -item[1]
    ):
        lines.append(f"- `{name}`: {count}")
    lines += ["", "## Overclaims by binding", ""]
    for name, count in sorted(
        report["overclaim_by_binding"].items(), key=lambda item: -item[1]
    ):
        lines.append(f"- `{name}`: {count}")
    lines += ["", "## Overclaims", ""]
    for row in report["overclaims"]:
        lines.append(
            f"- `{row['scope']}/{row['storage']}/{row['binding']}` "
            f"`{row['request']}` [{row['traits']}]: {row['result']}"
        )
    lines += ["", "## Declared gaps by reason", ""]
    for reason, count in sorted(
        report["declared_failure_by_reason"].items(),
        key=lambda item: -item[1],
    ):
        lines.append(f"- {reason}: {count}")
    lines += ["", "## Stale declarations by reason", ""]
    for reason, count in sorted(
        report["declared_success_by_reason"].items(),
        key=lambda item: -item[1],
    ):
        lines.append(f"- {reason}: {count}")
    lines += ["", "## Stale declarations", ""]
    for row in report["declared_successes"]:
        lines.append(
            f"- `{row['scope']}/{row['storage']}/{row['binding']}` "
            f"`{row['request']}` [{row['traits']}]"
        )
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--outcomes", type=Path, nargs="+")
    parser.add_argument("--outcomes-dir", type=Path)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--json", type=Path)
    arguments = parser.parse_args()

    paths = list(arguments.outcomes or [])
    if arguments.outcomes_dir is not None:
        paths.extend(
            sorted(arguments.outcomes_dir.glob("resolve-*.jsonl"))
        )
    if not paths:
        raise SystemExit("no resolve outcome files")
    report = compare(
        read_manifest(arguments.manifest),
        read_outcomes(paths),
    )
    arguments.out.parent.mkdir(parents=True, exist_ok=True)
    arguments.out.write_text(render(report), encoding="utf-8")
    if arguments.json is not None:
        arguments.json.write_text(
            json.dumps(report, indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
        )


if __name__ == "__main__":
    main()
